  }
  if ($SkipWebhook) { $argList += '-SkipWebhook' }
  if ($Force) { $argList += '-Force' }

  Start-Process -FilePath 'powershell.exe' -Verb RunAs -ArgumentList $argList -Wait
  exit $LASTEXITCODE
}

