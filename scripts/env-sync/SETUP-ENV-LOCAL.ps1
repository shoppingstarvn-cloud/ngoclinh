function Find-ProjectRoot {
  $parentOfScript = Split-Path -Parent $PSScriptRoot
  $grandParent = Split-Path -Parent $parentOfScript
  $candidates = @(
    $grandParent,
    $parentOfScript,
    $PSScriptRoot,
    (Get-Location).Path,
    'D:\SUPPER APP TRIEU DO\webbetonglammau'
  )

  foreach ($c in $candidates) {
    if ([string]::IsNullOrWhiteSpace($c)) { continue }
    $envEx = Join-Path $c '.env.example'
    $pkg = Join-Path $c 'package.json'
    if ((Test-Path -LiteralPath $envEx) -and (Test-Path -LiteralPath $pkg)) {
      return (Resolve-Path -LiteralPath $c).Path
    }
  }

  $dir = $PSScriptRoot
  for ($i = 0; $i -lt 6; $i++) {
    $envEx = Join-Path $dir '.env.example'
    if (Test-Path -LiteralPath $envEx) {
      return (Resolve-Path -LiteralPath $dir).Path
    }
    $parent = Split-Path -Parent $dir
    if ([string]::IsNullOrWhiteSpace($parent) -or ($parent -eq $dir)) { break }
    $dir = $parent
  }

  throw 'Khong tim thay thu muc goc du an (thieu .env.example + package.json).'
}

function Parse-EnvFile {
  param([Parameter(Mandatory = $true)][string]$Path)

  $map = [ordered]@{}
  $lines = Get-Content -LiteralPath $Path -Encoding UTF8
  foreach ($raw in $lines) {
    $line = $raw.Trim()
    if ([string]::IsNullOrWhiteSpace($line)) { continue }
    if ($line.StartsWith('#')) { continue }

    $idx = $line.IndexOf('=')
    if ($idx -lt 1) { continue }

    $key = $line.Substring(0, $idx).Trim()
    $val = $line.Substring($idx + 1).Trim()

    if ($val.Length -ge 2) {
      $q1 = $val.StartsWith('"') -and $val.EndsWith('"')
      $q2 = $val.StartsWith("'") -and $val.EndsWith("'")
      if ($q1 -or $q2) {
        $val = $val.Substring(1, $val.Length - 2)
      }
    }

    $map[$key] = $val
  }
  return $map
}

function New-ComplexSecret {
  param([int]$Length = 32)

  $alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#$%^&*-_=+'
  $bytes = New-Object byte[] $Length
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try {
    $rng.GetBytes($bytes)
  }
  finally {
    $rng.Dispose()
  }

  $chars = New-Object char[] $Length
  for ($i = 0; $i -lt $Length; $i++) {
    $chars[$i] = $alphabet[$bytes[$i] % $alphabet.Length]
  }
  return (-join $chars)
}

function ConvertFrom-SecureStringPlain {
  param([Parameter(Mandatory = $true)][Security.SecureString]$Secure)

  $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($Secure)
  try {
    return [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
  }
  finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
  }
}

function Write-EnvLocal {
  param(
    [Parameter(Mandatory = $true)][string]$Path,
    [Parameter(Mandatory = $true)][hashtable]$Values
  )

  $stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
  $lines = @(
    '# ============================================================',
    '# .env.local - auto generated by SETUP-ENV-LOCAL.ps1',
    ('# Generated: {0}' -f $stamp),
    '# DO NOT commit this file to Git.',
    '# ============================================================',
    '',
    '# Supabase - public (RLS protected)',
    ('NEXT_PUBLIC_SUPABASE_URL={0}' -f $Values['NEXT_PUBLIC_SUPABASE_URL']),
    ('NEXT_PUBLIC_SUPABASE_ANON_KEY={0}' -f $Values['NEXT_PUBLIC_SUPABASE_ANON_KEY']),
    '',
    '# Supabase - SECRET (server-only)',
    ('SUPABASE_SERVICE_KEY={0}' -f $Values['SUPABASE_SERVICE_KEY']),
    ('SUPABASE_BUCKET={0}' -f $Values['SUPABASE_BUCKET']),
    '',
    '# Auth admin JWT',
    ('JWT_SECRET={0}' -f $Values['JWT_SECRET']),
    '',
    '# Public site URL',
    ('NEXT_PUBLIC_SITE_URL={0}' -f $Values['NEXT_PUBLIC_SITE_URL']),
    ''
  )

  $utf8NoBom = New-Object System.Text.UTF8Encoding $false
  [System.IO.File]::WriteAllLines($Path, $lines, $utf8NoBom)
}

